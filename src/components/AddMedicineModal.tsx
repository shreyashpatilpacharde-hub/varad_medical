import React, { useState } from 'react';
import { X, PlusCircle, Pill, AlertCircle, Info } from 'lucide-react';
import { usePharmacy } from '../context/PharmacyContext.js';

interface AddMedicineModalProps {
  isOpen: boolean;
  onClose: () => void;
}

export const AddMedicineModal: React.FC<AddMedicineModalProps> = ({ isOpen, onClose }) => {
  const { addNewMedicine } = usePharmacy();
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [errorMsg, setErrorMsg] = useState<string | null>(null);

  // Strictly the 6 requested fields:
  // 1. Brand Name
  // 2. Tablet Name
  // 3. Expiry Date
  // 4. Available Stock (Total individual tablets, not strips)
  // 5. MRP
  // 6. GST Rate
  const [formData, setFormData] = useState({
    brandName: '',
    tabletName: '',
    expiryDate: '',
    availableStock: '',
    mrp: '',
    gstRate: '12',
  });

  if (!isOpen) return null;

  const handleChange = (e: React.ChangeEvent<HTMLInputElement | HTMLSelectElement>) => {
    setFormData(prev => ({ ...prev, [e.target.name]: e.target.value }));
    if (errorMsg) setErrorMsg(null);
  };

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();

    if (!formData.brandName.trim()) {
      setErrorMsg('Please enter the Brand Name.');
      return;
    }
    if (!formData.tabletName.trim()) {
      setErrorMsg('Please enter the Tablet Name (Generic / Formulation name).');
      return;
    }
    if (!formData.expiryDate) {
      setErrorMsg('Please select the Expiry Date.');
      return;
    }
    if (!formData.availableStock || isNaN(parseInt(formData.availableStock, 10)) || parseInt(formData.availableStock, 10) < 0) {
      setErrorMsg('Please enter a valid Available Stock in total individual tablets.');
      return;
    }
    if (!formData.mrp || isNaN(parseFloat(formData.mrp)) || parseFloat(formData.mrp) <= 0) {
      setErrorMsg('Please enter a valid MRP amount (₹).');
      return;
    }

    const availableQty = parseInt(formData.availableStock, 10);
    const mrp = parseFloat(formData.mrp);
    const gstRate = parseFloat(formData.gstRate) || 0;

    setIsSubmitting(true);
    setErrorMsg(null);

    const res = await addNewMedicine({
      name: formData.brandName.trim(),
      genericName: formData.tabletName.trim(),
      category: 'General Medicine',
      batchNumber: '', // Auto-generated by backend
      expiryDate: formData.expiryDate,
      availableQty,
      reorderLevel: 10,
      unit: 'tablets', // Always strictly individual tablets
      mrp,
      purchaseRate: Number((mrp * 0.7).toFixed(2)),
      gstRate,
      manufacturer: 'Varad Pharma Suppliers',
      locationRack: 'Main Dispensary',
    });

    setIsSubmitting(false);

    if (res.success) {
      onClose();
      // Reset form to clean state
      setFormData({
        brandName: '',
        tabletName: '',
        expiryDate: '',
        availableStock: '',
        mrp: '',
        gstRate: '12',
      });
    } else {
      setErrorMsg(res.error || 'Failed to add medicine');
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/50 backdrop-blur-xs overflow-y-auto">
      <div className="relative w-full max-w-xl bg-white rounded-xl shadow-2xl border border-slate-200 overflow-hidden my-6 animate-in fade-in zoom-in-95 duration-150">
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-slate-200 bg-teal-50/70">
          <div className="flex items-center gap-2.5">
            <div className="w-8 h-8 rounded-lg bg-teal-700 text-white flex items-center justify-center">
              <Pill className="w-4 h-4" />
            </div>
            <div>
              <h2 className="text-base font-bold text-slate-900">Add Medicine</h2>
              <p className="text-xs text-slate-500">
                Register new medicine stock for Varad Medical
              </p>
            </div>
          </div>
          <button
            type="button"
            onClick={onClose}
            className="p-1.5 text-slate-400 hover:text-slate-700 rounded-md transition-colors"
            aria-label="Close"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Error notice */}
        {errorMsg && (
          <div className="mx-6 mt-4 p-3 bg-red-50 border border-red-200 rounded-lg text-xs text-red-700 flex items-center gap-2">
            <AlertCircle className="w-4 h-4 shrink-0 text-red-500" />
            <span>{errorMsg}</span>
          </div>
        )}

        {/* Available Stock Guideline Notice */}
        <div className="mx-6 mt-4 p-3 bg-sky-50 border border-sky-200 rounded-lg text-xs text-sky-900 flex items-start gap-2">
          <Info className="w-4 h-4 shrink-0 text-sky-600 mt-0.5" />
          <div>
            <span className="font-semibold">Available Stock Rule:</span> Enter the total count of individual tablets available (not strips). For example, 5 strips containing 10 tablets each = <strong>50 tablets</strong>.
          </div>
        </div>

        {/* Form with strictly the 6 requested fields */}
        <form onSubmit={handleSubmit} className="p-6 space-y-4">
          {/* Field 1: Brand Name */}
          <div>
            <label className="block text-xs font-semibold text-slate-700 mb-1">
              Brand Name *
            </label>
            <input
              type="text"
              name="brandName"
              required
              placeholder="e.g. Dolo 650, Augmentin 625, Pan-D"
              value={formData.brandName}
              onChange={handleChange}
              className="w-full px-3 py-2 text-sm border border-slate-300 rounded-lg focus:outline-none focus:ring-2 focus:ring-teal-600 bg-white"
            />
          </div>

          {/* Field 2: Tablet Name */}
          <div>
            <label className="block text-xs font-semibold text-slate-700 mb-1">
              Tablet Name *
            </label>
            <input
              type="text"
              name="tabletName"
              required
              placeholder="e.g. Paracetamol 650mg, Amoxicillin + Clavulanate"
              value={formData.tabletName}
              onChange={handleChange}
              className="w-full px-3 py-2 text-sm border border-slate-300 rounded-lg focus:outline-none focus:ring-2 focus:ring-teal-600 bg-white"
            />
          </div>

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            {/* Field 3: Expiry Date */}
            <div>
              <label className="block text-xs font-semibold text-slate-700 mb-1">
                Expiry Date *
              </label>
              <input
                type="date"
                name="expiryDate"
                required
                value={formData.expiryDate}
                onChange={handleChange}
                className="w-full px-3 py-2 text-sm border border-slate-300 rounded-lg focus:outline-none focus:ring-2 focus:ring-teal-600 bg-white"
              />
              <span className="text-[10px] text-slate-400 mt-0.5 block">
                Medicines expiring within 1 month trigger an Expiry Alert
              </span>
            </div>

            {/* Field 4: Available Stock (Total individual tablets) */}
            <div>
              <label className="block text-xs font-semibold text-slate-700 mb-1">
                Available Stock (Tablets) *
              </label>
              <div className="relative">
                <input
                  type="number"
                  name="availableStock"
                  required
                  min="0"
                  placeholder="e.g. 50"
                  value={formData.availableStock}
                  onChange={handleChange}
                  className="w-full px-3 py-2 text-sm font-mono border border-slate-300 rounded-lg focus:outline-none focus:ring-2 focus:ring-teal-600 bg-white pr-16"
                />
                <span className="absolute right-3 top-2.5 text-xs text-slate-400 font-medium pointer-events-none">
                  tablets
                </span>
              </div>
              <span className="text-[10px] text-slate-500 mt-0.5 block font-mono">
                Total tablets (e.g., 5 strips × 10 = 50)
              </span>
            </div>
          </div>

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            {/* Field 5: MRP */}
            <div>
              <label className="block text-xs font-semibold text-slate-700 mb-1">
                MRP (₹ per tablet) *
              </label>
              <div className="relative">
                <span className="absolute left-3 top-2 text-sm text-slate-400 font-mono">₹</span>
                <input
                  type="number"
                  step="0.01"
                  min="0.1"
                  name="mrp"
                  required
                  placeholder="0.00"
                  value={formData.mrp}
                  onChange={handleChange}
                  className="w-full pl-7 pr-3 py-2 text-sm font-mono border border-slate-300 rounded-lg focus:outline-none focus:ring-2 focus:ring-teal-600 bg-white"
                />
              </div>
              <span className="text-[10px] text-slate-400 mt-0.5 block">
                Maximum retail price per individual tablet
              </span>
            </div>

            {/* Field 6: GST Rate */}
            <div>
              <label className="block text-xs font-semibold text-slate-700 mb-1">
                GST Rate (%) *
              </label>
              <select
                name="gstRate"
                value={formData.gstRate}
                onChange={handleChange}
                className="w-full px-3 py-2 text-sm border border-slate-300 rounded-lg focus:outline-none focus:ring-2 focus:ring-teal-600 bg-white"
              >
                <option value="0">0% (Nil / Exempted)</option>
                <option value="5">5% (Life-saving &amp; Essential)</option>
                <option value="12">12% (Standard Formulations)</option>
                <option value="18">18% (Disinfectants &amp; Special)</option>
                <option value="28">28% (Luxury / Cosmetic)</option>
              </select>
              <span className="text-[10px] text-slate-400 mt-0.5 block">
                Applicable GST tax slab for invoice record
              </span>
            </div>
          </div>

          {/* Form Actions */}
          <div className="pt-4 border-t border-slate-200 flex items-center justify-end gap-3">
            <button
              type="button"
              onClick={onClose}
              disabled={isSubmitting}
              className="px-4 py-2 text-xs font-medium text-slate-700 hover:text-slate-900 bg-white hover:bg-slate-100 border border-slate-300 rounded-lg transition-colors"
            >
              Cancel
            </button>
            <button
              type="submit"
              disabled={isSubmitting}
              className="px-5 py-2 text-xs font-bold text-white bg-teal-700 hover:bg-teal-800 disabled:opacity-50 rounded-lg transition-colors flex items-center gap-1.5 shadow-sm"
            >
              <PlusCircle className="w-4 h-4" />
              <span>{isSubmitting ? 'Adding Stock...' : 'Save Medicine'}</span>
            </button>
          </div>
        </form>
      </div>
    </div>
  );
};
